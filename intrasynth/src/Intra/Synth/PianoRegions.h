// Piano partial table, PACKED (11 bytes/row vs the readable 14 B/row struct):
//   K:6, Phase:8, Amp:11, Decay1:11, Decay2:11, Decay3:11, Decay4:11, FreqRatio:16
//   (little-endian bit stream; 3 pad bits at the end of each row)
// Amp/Decay are log2-quantized: q = 1 + round(128*log2(v)) for v>0, 0 for v==0;
// decode v = round(2^((q-1)/128)). Relative error <= 2^(1/128)-1 ~= 0.54%
// (~0.05 dB) — inaudible. FreqRatio/Phase/K are lossless.
// The readable source of truth and this generator live in .scratch/
// (PianoRegions.readable.h + pack-piano-table.js).
#pragma once

struct PianoPartial { uint8 K; uint8 Phase; uint16 Amp; uint16 Decay1; uint16 Decay2; uint16 Decay3; uint16 Decay4; uint16 FreqRatio; };
struct PianoRegionData { int RootKey; float F0; float AttackT; float DecayOnset; float SegT; float SegT2; float SegT3; float SampleLen; float Loudness; int PartCount; uint16 PartOffset; float HammerLevel; float StereoPan; };

static const size_t PianoPartialPackedSize = 11;

// Log2-quantized U16 decode (see header comment).
static inline uint16 PianoUnpackLogU16(unsigned q)
{
	if(q == 0) return 0;
	return uint16(Math::Pow(2.0f, float(q - 1)*(1.0f/128.0f)) + 0.5f);
}

// Decode one packed partial (11 bytes, little-endian bit stream).
static inline PianoPartial PianoDecodePartial(const uint8* p)
{
	unsigned long long lo = 0; // bits 0..63
	for(int i = 0; i < 8; i++) lo |= (unsigned long long)p[i] << (8*i);
	const unsigned hi = (unsigned)p[8] | ((unsigned)p[9] << 8) | ((unsigned)p[10] << 16); // bits 64..87
	PianoPartial r;
	r.K = uint8(lo & 0x3F);
	r.Phase = uint8((lo >> 6) & 0xFF);
	r.Amp = PianoUnpackLogU16(unsigned((lo >> 14) & 0x7FF));
	r.Decay1 = PianoUnpackLogU16(unsigned((lo >> 25) & 0x7FF));
	r.Decay2 = PianoUnpackLogU16(unsigned((lo >> 36) & 0x7FF));
	r.Decay3 = PianoUnpackLogU16(unsigned((lo >> 47) & 0x7FF));
	r.Decay4 = PianoUnpackLogU16(unsigned(((lo >> 58) & 0x3F) | ((hi & 0x1F) << 6)));
	r.FreqRatio = uint16((hi >> 5) & 0xFFFF);
	return r;
}

