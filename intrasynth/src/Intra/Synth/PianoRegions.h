// Decode one packed partial by row index from the given table. Lives at the
// end of the region block so the packer passes it through verbatim.
// ---- Per-instrument SF2-derived tables ----------------------------------
// INTRA_PIANO_ALL_TABLES (CMake option, default OFF = minimal build) compiles
// per-instrument coefficient tables; each instrument selects one via its
// TableId (AdditivePianoInstrument). Without the define only the shared
// acoustic table exists and every TableId resolves to it — zero extra bytes.
enum PianoTableId
{
	PianoTableShared = 0,
	PianoTableHonkyTonk = 1,
	PianoTableElectricGrand = 2,   // GM prog 2 (Roland XP50 EPiano)
	PianoTableElectricPiano1 = 3,  // GM prog 4 (Rhodes EVP73)
	PianoTableElectricPiano2 = 4,  // GM prog 5 (Yamaha DX7)
	PianoTableHarpsichord = 5,     // GM prog 6 (Harpsichord 8'I)
	PianoTableClavinet = 6,        // GM prog 7
};

struct PianoTable
{
	const PianoRegionData* Regions;
	const uint8* Partials;
	size_t RegionCount;
};

static inline PianoPartial PianoGetPartial(const PianoTable& t, size_t row)
{
	return PianoDecodePartial(t.Partials + row*PianoPartialPackedSize);
}

#ifdef INTRA_PIANO_ALL_TABLES
// Per-instrument tables (Electric Grand/Rhodes/DX7/Harpsichord/Clavinet,
// GM progs 2/4/5/6/7), generated by .scratch/gen-instrument-tables.js.
// Excluded from the minimal build (empty here) — the "all tables" build
// adds ~11 KB packed partial data for them.
#include "PianoTablesExtra.h"
#endif


static inline const PianoTable& PianoGetTable(int tableId)
{
#ifdef INTRA_PIANO_ALL_TABLES
	// Honky-Tonk (prog 3): the Titanic SF2 preset reuses the SAME Clavinova
	// samples as the acoustic grand (instrument "ClavinovaGrand mono"),
	// analysed 2026-08-30 — its character is the preset's detune, not new
	// samples — so its table aliases the shared one (zero extra bytes).
	// Instruments with distinct samples (Electric Grand CP-80, Rhodes, DX7,
	// Harpsichord, Clavinet) get their own Regions/Partials arrays here.
	if(tableId == PianoTableHonkyTonk)
	{
		static const PianoTable ht = { PianoSampleRegions, PianoAllPartialsPacked, PianoSampleRegionCount };
		return ht;
	}
	if(tableId == PianoTableElectricGrand)
	{
		static const PianoTable eg = { PianoEGRegions, PianoEGPartialsPacked, PianoEGRegionCount };
		return eg;
	}
	if(tableId == PianoTableElectricPiano1)
	{
		static const PianoTable ep1 = { PianoEP1Regions, PianoEP1PartialsPacked, PianoEP1RegionCount };
		return ep1;
	}
	if(tableId == PianoTableElectricPiano2)
	{
		static const PianoTable ep2 = { PianoEP2Regions, PianoEP2PartialsPacked, PianoEP2RegionCount };
		return ep2;
	}
	if(tableId == PianoTableHarpsichord)
	{
		static const PianoTable har = { PianoHARRegions, PianoHARPartialsPacked, PianoHARRegionCount };
		return har;
	}
	if(tableId == PianoTableClavinet)
	{
		static const PianoTable clav = { PianoCLAVRegions, PianoCLAVPartialsPacked, PianoCLAVRegionCount };
		return clav;
	}
#endif
	static const PianoTable shared = { PianoSampleRegions, PianoAllPartialsPacked, PianoSampleRegionCount };
	return shared;
}


