/// Фабрика модальной струны (программы 29/30). Все числа — из
/// intrasynth/tools/instruments/guitar-modal.json.
struct SpectralStringInstrument
{
	// --- ЗАТРАВКА KS (Update 106) ---
	// Damping — шум медиатора в щипке (то же поле, что у KarplusStrongInstrument:
	// 0.05 у AcousticGuitarSteel). SfBase/SfMul/SfExp — формула сглаживающего
	// коэффициента петли KS: sf = SfBase·(0.9 − (note/128)^SfExp·SfMul + rand·0.1).
	// Она задаёт и форму щипка (через зерно генератора), и закон потерь:
	// rate_k = −f0·ln|H(2πf_k/f_s)|, где H = (1−sf)/(1−sf·z⁻¹) — однополюсник
	// петли KS, то есть затухание СВОЕЙ гармоники за период.
	float Damping = 0.05f;
	float SfBase = 0.25f;
	float SfMul = 0.8f;
	float SfExp = 0.5f;
	// Общий экспоненциальный спад KS (у steel 1.0): у перегруза он может быть
	// меньше — нота тянется дольше, а верх под клипером живёт за счёт RateCap.
	float ExpCoeff = 1.0f;
	// Предел скорости потерь гармоники (1/с), 0 — чистый KS. У KS верх гаснет
	// очень быстро (∝f²·f0), и к моменту, когда клипер должен «докрашивать»
	// спектр, на входе остаётся почти синус — перегруз звучит бедно. Предел
	// оставляет верх живым ровно настолько, чтобы нелинейности было что резать.
	float RateCap = 0;
	// ЗАТУХАНИЕ ОТ ЧАСТОТЫ — ВНУТРЕННЕЕ ТРЕНИЕ СТРУНЫ (Update 110). Добавка к
	// скорости потерь гармоники, пропорциональная её частоте: dampSlope·(f_k−f0),
	// в 1/с на кГц. Почему это нужно: у закона KS первые пять-шесть гармоник
	// гаснут почти ОДИНАКОВО (замер .scratch/guitar-drift110.mjs: h2 гаснет
	// 0.7 дБ/с, h10 — 17 дБ/с), то есть относительные амплитуды низких гармоник
	// не меняются и форма периода ЗАМОРОЖЕНА — нота звучит одной и той же
	// «пилой/прямоугольником» от начала до конца. У банка дрейф тембра 12.6 дБ,
	// у нас был 3.9. Берётся разность (f_k−f0), а не сама частота: так основной
	// тон (а с ним длина и сустейн ноты) не трогается, а гармоники расходятся
	// с ним по скорости — нота «гладеет», как у банка.
	//
	// ПОЧЕМУ ОСТАЁТСЯ СКАЛЯРОМ (проверено в Update 120). Через то, что эта добавка
	// ∝ (f_k − f0), она на низких нотах почти не работает, а на высоких огромна:
	// полоса 2-4 кГц от атаки к сустейну у банка на E2 гаснет на 49 дБ, у нас —
	// на 21 (низ заморожен), а на E5 банк меняется лишь на 7.5 дБ, у нас — на 26
	// (верх пересушен). Однако региональный DampSlope (собран, проверен на
	// нейтральность при равных якорях — расхождение 0, и прогнан свипом по
	// 10 нотам с добавленным окном сустейна) оценку НЕ улучшил: 8.26 дБ у единого
	// 0.6 против 8.27…8.29 у лучших троек, а подъём низа — до 11.2. Значит дрейф
	// низа упирается в другое (полоса среднего верха, а не скорость потерь).
	float DampSlope = 0;
	// НАКЛОН ДАТЧИКА В ЕДИНИЦАХ «+6 дБ/окт» (Update 110): амплитуда моды k
	// домножается на k^TiltExp. Магнитный датчик меряет скорость струны, то есть
	// действительно даёт +6 дБ/окт — но у нас эта надбавка ложится на спектр щипка
	// ~1/k², и вместе выходит ровно 1/k: ПЛОСКИЙ, «пилообразный» спектр (замер:
	// h2..h6 в пределах 5 дБ друг от друга, у банка — −15…−33 дБ отн. h1).
	// TiltExp = 1 — прежнее поведение (Updates 106-109), меньше — глаже.
	//
	// ПО РЕГИОНАМ (Update 122). Единый TiltExp не описывает обе стороны: замер
	// ряда h2..h12 отн. h1 на ТИХОЙ ноте (velocity 40 — клипер не работает, видно
	// саму струну) против банка, RMSE по клавишам E3/E4:
	//   TiltExp 1.0 — 11.38 / 11.00 дБ, TiltExp 0.6 — 10.05 / 10.60,
	//   TiltExp 0.4 — 7.39 / 3.62 дБ.
	// То есть низ и середина требуют заметно более гладкой струны (верхние
	// гармоники у нас на 10 дБ горячее банковских от h4 и выше — это и есть
	// «дребезжание, слышное на всех нотах, включая тихие»), а верх (E5/E6) на
	// 0.4 наоборот портится (10.06/16.29 → 10.64/18.19). Региональность даёт
	// каждому участку свой наклон.
	SpectralStringRegion TiltExp;
	// НЕГАРМОНИЧНОСТЬ — ЖЁСТКОСТЬ СТРУНЫ, коэффициент B в f_k = k·f₀·√(1 + B·k²).
	// С Update 113 это НАСТОЯЩИЙ сдвиг частот (моды ставятся на свою частоту на
	// сетке буфера из InharmPeriods периодов), а не поворот фазы.
	//
	// ИСТОРИЯ ОШИБКИ (не повторять): истинную НЕКРАТНОСТЬ буфер ОДНОГО периода
	// дать не может, и
	// замер это подтвердил (.scratch/guitar-peaks112.mjs): буфер одного периода
	// может нести только моды, укладывающиеся в него ЦЕЛОЕ число циклов, то есть
	// строго кратные f₀. Поворот фазы за период (mRotC/mRotS) частоты НЕ двигает:
	// внутри периода мода остаётся на бине k, а сам доворот даёт боковые
	// составляющие на кратных f₀ — пики остаются ровно на сетке (замер: 261.8,
	// 523.5, 785.3 Гц против номинала 261.7, 523.4, 785.1).
	//
	// Что он всᑑ-таки делает: относительная фаза моды k идёт со скоростью
	// 2π(f_k − k·f₀) — РАВНОЙ истинной негармонической, поэтому форма периода
	// перестаёт быть замороженной и «переливается» с правильной скоростью
	// (через клипер это слышно: уровни гармоник после клипа плывут), но мусор
	// оказался дороже пользы; теперь частоты сдвигаются по-настоящему.
	//
	// InharmPeriods — СКОЛЬКО ПЕРИОДОВ В БУФЕРЕ: 1 — моды кратны (негармоничности
	// нет), 8 — сетка f₀/8, этого достаточно всем слышимым модам. Память и БПФ
	// растут как InharmPeriods, поэтому длина ограничена 8192 отсчётами (на низах
	// число периодов само уменьшается).
	//
	// По РЕГИОНАМ (E2/E4/E6): у банка негармоничность на низах и верхах
	// отличается на порядок (замер .scratch/guitar-inharm112.mjs: B ≈ 1e-4 на E2
	// против ~0 на C5/C6, где сэмплы закольцованы целым числом периодов).
	SpectralStringRegion Inharm;
	uint InharmPeriods = 1;
	// БИЕНИЯ ПОЛЯРИЗАЦИЙ — СЛЫШИМАЯ «БОГАТОСТЬ» (Update 112). У реальной струны
	// колебание идёт в ДВУХ плоскостях; их частоты различаются на доли процента,
	// и пары близких частот бьют друг друга. Биения слышны прямо (в отличие от
	// дрейфа фаз, к которому ухо в установившемся тоне глухо) и дают именно то,
	// что просил владелец: тембр не «просто затухает», а «переливается» —
	// огибающая пульсирует, а не падает монотонно.
	// Реализовано модуляцией амплитуды каждой моды в спектре (ДО клипера, поэтому
	// через нелинейность слышно сильнее, как у настоящего усилителя):
	//   A_k → A_k·(1 + BeatDepth·cos(2π·ν_k·t + θ_k)),  ν_k = k·BeatSplit·f₀.
	// Закон ν_k ∝ частоте моды — такой же, как у реальной пары поляризаций или
	// удвоенной дорожки. θ_k — детерминированная фаза по номеру моды (без таблиц).
	// BeatDepth = 0 — выключено (прежнее поведение бит-в-бит).
	float BeatSplit = 0;
	float BeatDepth = 0;
	// --- ДАТЧИК И ГЕОМЕТРИЯ (не физика струны, а тракт) ---
	// ГЛУБИНА НУЛЕЙ КОМБА ДАТЧИКА (Update 115). Раньше здесь было одно число на
	// C6 (PickupDepthMin), и глубина комба была максимальной ровно там, где нули
	// НЕ совпадают с гармониками (низкие клавиши), а на верхах ослаблялась.
	// Замер (.scratch/guitar-harm115e.mjs) показал обратное: у НАС на C4 чётные
	// гармоники выбиты на 13-16 дБ относительно нечётных (нечётность +10.4 дБ),
	// а у банка Titanic того же пресета — 1-3 дБ, то есть спектр РОВНЫЙ.
	// Причина геометрическая: q = pickup·f/261.63 упирается в кламп 0.5, а при
	// q = 0.5 нули 1 − z^(−q·N) стоят РОВНО на чётных гармониках на ВСЕХ клавишах
	// выше A#4 — спектр становится «только нечётные», а это и есть прямоугольная
	// волна (замер: крест-фактор одного периода 1.4-1.5 против банковских 1.9).
	//
	// Теперь глубина задана ЧЕСТНО: PickupDepth — глубина нулей на НИЗКИХ модах,
	// PickupAperture — доля длины струны, которую датчик УСРЕДНЯЕТ (апертура
	// катушки). Апертура и есть физическая причина, по которой у реальной струны
	// нули не бесконечные: усреднение по длине гасит моду тем сильнее, чем короче
	// её волна, поэтому depth_k = PickupDepth·sinc(π·Aperture·k) — высокие моды
	// нулей не видят вовсе, и спектр заполняется, как у банка.
	float PickupDepth = 0.5f;
	float PickupAperture = 0.15f;
	// ПРЕДЕЛ СУСТЕЙНА (Update 115; РЕГИОНАЛЬНЫЙ с Update 116): во сколько раз
	// канал может поднять уровень на входе клипера по мере затухания струны
	// (1 — выключено, тогда клипер гаснет вместе со струной и нота «уходит в
	// синус»).
	//
	// ПОЧЕМУ РЕГИОНАЛЬНЫЙ (замер Update 116, .scratch/guitar-bands116.mjs и
	// .scratch/guitar-buzz116.mjs): единое 4 = +12 дБ подъёма ПРОДОЛЖАЛО резать
	// струну всю ноту, и верх после клипера (3-8 кГц) в сустейне выходил на
	// 17-29 дБ горячее банка на E2/E4 — это и есть «ещё сильнее дребезжит».
	// Разница в том, что у банка сустейн высоких клавиш яркий (в его семпле
	// 3-14 кГц держатся), а у низких и средних верх гаснет вместе со струной.
	// Поэтому подъём нужен верхам (2.5) и почти не нужен низам (1).
	SpectralStringRegion SustainMax;
	// Добротность резонанса кабинета (0.7 — без горба, 1.1-1.3 — с «присутствием»).
	float CabQ = 1.15f;
	// Сколько секций кабинета (Update 116): 1 — один ФНЧ (12 дБ/окт, как в
	// Updates 108-115), 2 — каскад из двух (24 дБ/окт). Почему нужен второй —
	// см. замер в .scratch/guitar-bands116.mjs: остаточный верх 8-14 кГц
	// на 8-20 дБ горячее банка при сходящихся 3-8 кГц.
	//
	// ПО РЕГИОНАМ (Update 141) — и это НЕ украшение, а единственный способ
	// дотянуться до верха ВЫСОКИХ нот. Причина в геометрии региона: якоря лежат
	// на клавишах 52/76/100, а C6 — это 1/3 пути от якоря 76 к якорю 100, поэтому
	// ЛЮБАЯ «только для верха» величина (срез кабинета, полка) доходит до C6
	// ослабленной втрое. Замер собранной сборки (.scratch/u141-source.mjs):
	// в СУСТЕЙНЕ на C6 моды струны выше h4 мертвы (с выключенным драйвом h5 = −119 дБ),
	// то есть весь ряд h5…h11 (−58…−92 дБ, у банка −74…−109) рождает КЛИПЕР из почти
	// синусоидального входа. Потолок этого ряда задаёт не струна, а кабинет:
	// у банка падение от h4 к h8 — 57 дБ (≈36-48 дБ/окт), у нас 26 дБ (12 дБ/окт).
	// Поэтому у верха включена ВТОРАЯ секция (24 дБ/окт), а низ/середина остаются
	// на одной: кабина 24 дБ/окт от 40-й клавиши до C5+ (Update 123) делала верх
	// C3-C5 на 15-20 дБ темнее банковского (замер .scratch/u141-check.mjs).
	SpectralStringRegion CabPoles;
	// Срез низа ПОСЛЕ клипера (Гц, однополюсный ФВЧ — межкаскадный конденсатор;
	// Update 114). Снимает «walking DC» асимметричного клипера: без него
	// ниже фундаментала едет до −17 дБ энергии (на C6 это 18% амплитуды) и
	// портит форму волны (формофактор E2 0.885 против банковских 0.824).
	// 30 Гц безопасны для низкой ми E2 (82 Гц теряет ~0.3 дБ), 0 — выключено.
	float PostHpHz = 30.0f;
	// Pickup — точка звукоснимателя (доля длины струны от бриджа, задана для C4
	// и удваивается на октаву: датчик стоит на фиксированном расстоянии от
	// бриджа, а звучащая часть струны с высотой ноты короче). Даёт комб
	// 1 − z^(−q·N) — но С Update 115 он считается В ЧАСТОТНОЙ ОБЛАСТИ, по модам
	// (нули ровно на гармониках n/q при любой сетке БПФ), и его глубина падает с
	// номером моды из-за апертуры (см. PickupDepth/PickupAperture). Наклон
	// +6 дБ/окт остаётся: магнитный датчик меряет скорость струны.
	// 0 — датчика нет, струна звучит как «голая» (так и должно быть у затравки
	// KS: у steel-гитары в синтезаторе комба нет).
	SpectralStringRegion Pickup;
	// Региональные числа тракта (E2/E4/E6, Update 109): Scale — уровень после
	// клипера; PickupHz — полоса звукоснимателя/кабинета ДО клипера (Гц, 4-й
	// порядок; эмуляция датчика и антиалиасинг продуктов нелинейности); Drive —
	// глубина клипа (0 — чистая струна); Bias — асимметрия (0.1-0.3 даёт чётные
	// гармоники); ToneCutoff — срез верха после клипа (Гц, 0 — без среза).
	SpectralStringRegion Scale;
	SpectralStringRegion PickupHz;
	SpectralStringRegion Drive;
	SpectralStringRegion Bias;
	SpectralStringRegion ToneCutoff;
	// ТЕМБР-СТЕК ПОСЛЕ КАБИНЕТА — В КАНОНЕ (Update 130). Полка ВЧ (однополюсник,
	// см. GuitarTweaks.PresenceDb) была ручкой экспериментов с Update 126; замер
	// блочным путём (как играет браузер и панель, .scratch/u130-decide.mjs, шесть
	// клавиш 36/48/52/64/76/88) показал, что +12 дБ @2.5 кГц — СТРОГО лучше
	// канона по всем трём метрикам против банка: RMSE полос 10.62 → 9.15 дБ,
	// RMSE ряда гармоник 13.53 → 13.23, средняя |flat − банк| 21.0 → 3.5 %
	// (именно это владелец слышал как «пилообразный и без драйва» на C3: у банка
	// середина 800-2000 Гц и присутствие 2-4 кГц ВЫШЕ фундаментала, а у нас
	// ряд гармоник падал от фундаментала вниз). Числа — региональными НЕ стали:
	// полка даёт выигрыш на всех шести клавишах, включая E6 (flat 51.5 → 12.1 %).
	// Ручки панели при включении ПЕРЕКРЫВАЮТ эти числа (пресет canon ставит их же).
	float PresenceHz = 2500.0f;
	float PresenceDb = 0.0f;
	// ФОРМАНТНЫЙ ТРАКТ С ФИКСИРОВАННЫМИ ПО Гц ЧАСТОТАМИ (Update 150) — новое звено.
	// ЧТО ЭТО. Три секции тембр-стека (полка низа, резонансный пик присутствия,
	// полка верха), у которых частоты заданы В ГЕРЦАХ на весь инструмент, а не по
	// регионам и не по номеру гармоники. Стоят последним линейным звеном тракта.
	// ЧТО ЭТО ДАЁТ. Такая окраска на разных клавишах приходится на РАЗНЫЕ номера
	// гармоник, поэтому меняет ряд не монотонно и по-разному по клавиатуре —
	// именно так ведёт себя ряд банка (замеры .scratch/u150b-diff.mjs,
	// .scratch/u151-timbre.mjs: у 29 форма разницы «банк − мы» согласована по Гц
	// между клавишами, медиана корреляции 0.78). Прежние механизмы (TiltExp k^p,
	// комб датчика, DampSlope по (f_k − f0), ФНЧ кабинета, полка присутствия)
	// дают либо привязку к номеру моды, либо монотонный по частоте спад.
	// ЧИСЛА. Подобраны координатным спуском (.scratch/u152-fit.mjs) под разницу
	// усреднённых огибающих: СКО по 21 полосе 100 Гц - 10 кГц падает 2.92 -> 1.06 дБ
	// (29) и 3.50 -> 0.48 дБ (30). Ноль в Hz или в Db — секция не строится.
	// ПОРЯДОК ПОЛЕЙ — В КОНЦЕ СТРУКТУРЫ: агрегатная инициализация в
	// InstrumentLibrary.cpp связывает значения по месту (грабля Update 115).
	float ToneLowHz = 0;
	float ToneLowDb = 0;
	float TonePeakHz = 0;
	float TonePeakQ = 1;
	float TonePeakDb = 0;
	float ToneHighHz = 0;
	float ToneHighDb = 0;
	// Шума в струне НЕТ и не будет (Update 101): владелец дважды забраковал любой
	// ДОБАВЛЕННЫЙ шумовой слой в щипке. Шум здесь — только часть затравки KS
	// (шум медиатора в её возбуждении, Update 106), без него guitar steel теряет
	// узнаваемость; отдельного слоя и впрыска в тракт по-прежнему нет.
	GenericSamplerRef operator()(float freq, float volume, unsigned sampleRate) const
	{
		// Ручки живого эксперимента (Update 125): копия с масштабированными
		// числами. Копия — это POD-структура, стоит копейки при создании голоса;
		// в рендере ручек нет вовсе. Выключенные ручки — путь прежний.
		SpectralStringInstrument t = *this;
		if(GuitarTweakState.Enabled)
		{
			const GuitarTweaks& w = GuitarTweakState;
			t.Damping *= w.Damping;
			t.SfBase *= w.SfBase;
			t.ExpCoeff *= w.ExpCoeff;
			t.BeatDepth *= w.BeatDepth;
			t.PickupDepth *= w.PickupDepth;
			t.CabQ *= w.CabQ;
			t.TiltExp = {TiltExp.Low*w.Tilt, TiltExp.Mid*w.Tilt, TiltExp.High*w.Tilt};
			t.Inharm = {Inharm.Low*w.Inharm, Inharm.Mid*w.Inharm, Inharm.High*w.Inharm};
			t.SustainMax = {SustainMax.Low*w.SustainMax, SustainMax.Mid*w.SustainMax, SustainMax.High*w.SustainMax};
			t.Pickup = {Pickup.Low*w.Pickup, Pickup.Mid*w.Pickup, Pickup.High*w.Pickup};
			t.Scale = {Scale.Low*w.Scale, Scale.Mid*w.Scale, Scale.High*w.Scale};
			t.PickupHz = {PickupHz.Low*w.PickupHz, PickupHz.Mid*w.PickupHz, PickupHz.High*w.PickupHz};
			t.Drive = {Drive.Low*w.Drive, Drive.Mid*w.Drive, Drive.High*w.Drive};
			t.Bias = {Bias.Low*w.Bias, Bias.Mid*w.Bias, Bias.High*w.Bias};
			t.ToneCutoff = {ToneCutoff.Low*w.Tone, ToneCutoff.Mid*w.Tone, ToneCutoff.High*w.Tone};
			t.DampSlope *= w.DampSlope;
			t.PresenceHz = w.PresenceHz;
			t.PresenceDb = w.PresenceDb;
			// Тембр-стек тракта (Update 150): усиления секций — МНОЖИТЕЛЬ (0 —
			// звено выключено, как у «чистой струны»), частота и добротность
			// пика — АБСОЛЮТНЫЕ (0 — канон), полки — добавка в дБ.
			t.ToneLowDb = t.ToneLowDb*w.ToneStack + w.ToneStackLowDb;
			t.TonePeakDb = t.TonePeakDb*w.ToneStack;
			t.ToneHighDb = t.ToneHighDb*w.ToneStack + w.ToneStackHighDb;
			if(w.ToneStackPeakHz > 0) t.TonePeakHz = w.ToneStackPeakHz;
			if(w.ToneStackPeakQ > 0) t.TonePeakQ = w.ToneStackPeakQ;
		}
		SpectralToneStack tone;
		tone.Low.Hz = t.ToneLowHz;
		tone.Low.Db = t.ToneLowDb;
		tone.Low.Q = 0.9f;
		tone.Peak.Hz = t.TonePeakHz;
		tone.Peak.Q = t.TonePeakQ;
		tone.Peak.Db = t.TonePeakDb;
		tone.High.Hz = t.ToneHighHz;
		tone.High.Db = t.ToneHighDb;
		tone.High.Q = 0.9f;
		return new SpectralStringSampler(freq, volume, sampleRate,
			t.Damping, t.SfBase, t.SfMul, t.SfExp, t.ExpCoeff, t.RateCap, t.DampSlope, t.TiltExp, t.Inharm, t.InharmPeriods,
			t.BeatSplit, t.BeatDepth, t.PickupDepth, t.PickupAperture, t.SustainMax, t.CabQ, t.CabPoles, t.PostHpHz,
			t.Pickup, t.Scale, t.PickupHz, t.Drive, t.Bias, t.ToneCutoff,
			t.PresenceHz, t.PresenceDb, tone);
	}
};

